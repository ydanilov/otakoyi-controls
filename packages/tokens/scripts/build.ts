/**
 * Generates platform files from tokens.json:
 *  - generated/tokens.css            CSS variables (default brand, dark + light) for the web pult and builder
 *  - generated/tailwind-preset.cjs   Tailwind/NativeWind preset: semantic colours → CSS vars, spacing, radius, type
 *
 * `--check` fails if the committed files are stale (CI sensor).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createTheme, themeToCssVars, baseTokens as base } from "../src/theme";
import { brandDriftFromFigma, type FigmaBrandModes } from "../src/figma";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const header =
  "/* Generated by packages/tokens/scripts/build.ts — do not edit. Run `pnpm tokens`. */\n";

const block = (selector: string, vars: Record<string, string>) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n")}\n}\n`;

const css =
  header +
  block(":root, .dark", themeToCssVars(createTheme({ mode: "dark" }))) +
  "\n" +
  block(".light", themeToCssVars(createTheme({ mode: "light" })));

/** Entry stylesheet for NativeWind / Tailwind on every surface: directives + default theme variables. */
const globalCss =
  header +
  "@tailwind base;\n@tailwind components;\n@tailwind utilities;\n\n@layer base {\n" +
  css
    .replace(header, "")
    .split("\n")
    .map((l) => (l ? "  " + l : l))
    .join("\n") +
  "}\n";

const px = (o: Record<string, number>) =>
  Object.fromEntries(Object.entries(o).map(([k, v]) => [k, v === 9999 ? "9999px" : `${v}px`]));

const colorVars = [
  "background",
  "foreground",
  "card",
  "card-foreground",
  "popover",
  "popover-foreground",
  "primary",
  "primary-foreground",
  "secondary",
  "secondary-foreground",
  "muted",
  "muted-foreground",
  "accent",
  "accent-foreground",
  "brand-accent",
  "brand-accent-foreground",
  "destructive",
  "border",
  "input",
  "ring",
  "status-online",
  "status-warning",
  "status-critical",
  "status-offline",
  "status-studio",
  "control-track",
  "control-fill",
];

const preset = {
  theme: {
    extend: {
      colors: Object.fromEntries(colorVars.map((v) => [v, `rgb(var(--${v}) / <alpha-value>)`])),
      spacing: px(base.space),
      borderRadius: { ...px(base.radius), DEFAULT: "var(--radius)" },
      fontSize: Object.fromEntries(
        Object.entries(base.font.size).map(([k, v]) => [
          k,
          [
            `${v}px`,
            { lineHeight: `${base.font.lineHeight[k as keyof typeof base.font.lineHeight]}px` },
          ],
        ]),
      ),
      fontFamily: { sans: [base.font.family.sans], mono: [base.font.family.mono] },
      letterSpacing: Object.fromEntries(
        Object.entries(base.font.tracking).map(([k, v]) => [k, `${v}em`]),
      ),
      minHeight: { touch: `${base.touch.min}px` },
      minWidth: { touch: `${base.touch.min}px` },
    },
  },
};

const presetFile = `${header}module.exports = ${JSON.stringify(preset, null, 2)};\n`;

const files: Array<[string, string]> = [
  ["generated/tokens.css", css],
  ["generated/global.css", globalCss],
  ["generated/tailwind-preset.cjs", presetFile],
];

const check = process.argv.includes("--check");
let stale = 0;
for (const [rel, content] of files) {
  const path = join(root, rel);
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current !== content) {
      console.error(`✗ ${rel} is stale — run \`pnpm tokens\` and commit the result.`);
      stale++;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`✓ ${rel}`);
  }
}
// Figma Brand modes (figma/brand-modes.json, dumped from Figma) vs tokens.json brandDefaults.
const figma = JSON.parse(
  readFileSync(join(root, "figma/brand-modes.json"), "utf8"),
) as FigmaBrandModes;
for (const d of brandDriftFromFigma(figma, base.brandDefaults as Record<string, string>)) {
  console.error(`✗ Figma Brand drift: ${d}`);
  stale++;
}
if (stale) process.exit(1);
if (check) console.log("✓ generated token files are up to date; brandDefaults = Figma Brand");
